const TRANSLATIONS = { en, fr, de, nl, pt, es, sv, ro };

const I18nContext = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    if (typeof window === "undefined") return "en";
    const saved = window.localStorage.getItem(STORAGE_KEY);
    return saved && TRANSLATIONS[saved] ? saved : "en";
  });

  useEffect(() => {
    if (typeof window === "undefined") return;
    window.localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.setAttribute("lang", lang);
  }, [lang]);

  const value = useMemo(() => {
    const dict = TRANSLATIONS[lang] || en;
    const t = (key) => (key in dict ? dict[key] : (en[key] ?? key));
    return { lang, setLang, t };
  }, [lang]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useT() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useT must be used inside <I18nProvider>");
  return ctx;
}

// Fallback for non-component callers (e.g., toasts inside async helpers).
let activeLang = "en";
export function setActiveLang(l) {
  activeLang = TRANSLATIONS[l] ? l : "en";
}
export function tStatic(key) {
  const dict = TRANSLATIONS[activeLang] || en;
  return key in dict ? dict[key] : (en[key] ?? key);
}
